"""The notebook that materializes a bridge table in the sandbox Lakehouse (T-506, business rule 4).

Two sources of SQL, both read-only SELECTs that code has checked:
- a deterministic `SELECT DISTINCT` of an existing mapping table, when an approved deduplication
  rule allows removing its duplicate pairs (section 15);
- a SELECT the model drafted from an approved derivation rule (`bridge_sql.py`).
The notebook only creates its target table in `nexora_generated`, in the Lakehouse it is attached
to (the sandbox Lakehouse), and fails on an empty result. Output is deterministic for the same input.
"""

import json
import re
from pathlib import Path

TARGET_SCHEMA = "nexora_generated"
SAFE = re.compile(r"[^a-z0-9_]+")


def target_table(bridge_id: str, hint: str) -> str:
    """A stable, safe table name for a bridge: bridge_<id>_<hint>."""
    return f"bridge_{SAFE.sub('_', bridge_id.lower()).strip('_')}_{SAFE.sub('_', hint.lower()).strip('_')}"[:100]


def dedup_select(source_schema: str, source_table: str, columns: tuple[str, str]) -> str:
    """The deterministic deduplication of a mapping table: one row per pair, no null keys."""
    a, b = (f"`{c}`" for c in columns)
    return f"SELECT DISTINCT {a}, {b} FROM `{source_schema}`.`{source_table}` WHERE {a} IS NOT NULL AND {b} IS NOT NULL"


def build_notebook(
    bridge_id: str,
    select_sql: str,
    table: str,
    description: str,
    lakehouse: dict,
    schema: str = TARGET_SCHEMA,
) -> dict:
    """The notebook (nbformat 4) as a dict. `lakehouse` is {id, name, workspace_id}: the notebook's default."""
    if '"""' in select_sql:
        raise ValueError("the SQL can't contain triple quotes")
    target = f"`{schema}`.`{table}`"

    def code(*lines: str) -> dict:
        return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": list(lines)}

    cells = [
        {
            "cell_type": "markdown",
            "metadata": {},
            "source": [
                f"# Bridge {bridge_id}\n",
                "\n",
                f"{description}\n",
                "\n",
                f"Generated by Nexora. It writes only `{schema}.{table}` in the Lakehouse this notebook is attached to.\n",
            ],
        },
        code(f'spark.sql("CREATE SCHEMA IF NOT EXISTS `{schema}`")'),
        code(
            f'spark.sql("""CREATE OR REPLACE TABLE {target} USING DELTA AS\n',
            *[f"{line}\n" for line in select_sql.strip().splitlines()[:-1]],
            f'{select_sql.strip().splitlines()[-1]}""")',
        ),
        code(
            f'rows = spark.table("{schema}.{table}").count()\n',
            f'print("{schema}.{table}:", rows, "rows")\n',
            'assert rows > 0, "empty bridge"',
        ),
    ]
    return {
        "cells": cells,
        "metadata": {
            "kernel_info": {"name": "synapse_pyspark"},
            "kernelspec": {"name": "synapse_pyspark", "display_name": "Synapse PySpark"},
            "language_info": {"name": "python"},
            "microsoft": {"language": "python", "language_group": "synapse_pyspark"},
            "dependencies": {
                "lakehouse": {
                    "default_lakehouse": lakehouse["id"],
                    "default_lakehouse_name": lakehouse["name"],
                    "default_lakehouse_workspace_id": lakehouse["workspace_id"],
                }
            },
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def write_notebook(notebook: dict, path: Path) -> None:
    """Write UTF-8 with LF line endings (bytes, so Windows keeps LF)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes((json.dumps(notebook, indent=1, ensure_ascii=False) + "\n").encode("utf-8"))
