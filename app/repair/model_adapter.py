"""The semantic-model adapter of the repair service (T-505).

Fixes go into a candidate copy of the ModelSpec, never straight into files. The candidate is
serialized to a staging TMDL folder and compared with the version in place: only the files of the
failing objects (and of the objects a fix touched) may differ, otherwise the attempt is discarded.
A kept attempt becomes the next ModelSpec version and the next `model/v<n>` folder, and is
validated (appended to ValidationReport.json as a repair attempt).

Fixes: FORMAT_STRING_INVALID is deterministic (the invalid format string of the named measure or
column is dropped); a measure's DAX is regenerated by the model (`propose_measure_dax`, with the
failure as feedback and the usual reference pre-check) and only that measure changes.
"""

import shutil
from pathlib import Path
from typing import Any

from app.contracts.model_plan import ModelSpec, save_yaml, to_data
from app.contracts.validation_report import ValidationCheck, ValidationRun
from app.fsutil import replace_file
from app.llm.errors import LlmTimeout, LlmUpstreamError, PromptRejected
from app.model.dax_generator import DaxRejected, propose_measure_dax
from app.model.tmdl_generator import _file_name, generate_tmdl
from app.model.tmdl_reader import read_model
from app.repair.models import ClassifiedError
from app.repair.policy import RepairPolicy, named_objects, repair_code
from app.workflow.harvest_stage import canonical_hash
from app.workflow.model_stage import _next_version, folder_hash
from app.workflow.plan_stage import MODEL_FILE
from app.workflow.validate_stage import Environment, run_validation

ARTIFACT = "SemanticModel"


def read_tree(folder: Path) -> dict[str, bytes]:
    folder = Path(folder)
    return {p.relative_to(folder).as_posix(): p.read_bytes() for p in sorted(folder.rglob("*")) if p.is_file()}


def changed_files(previous: Path, new: Path) -> set[str]:
    a, b = read_tree(previous), read_tree(new)
    return {name for name in a.keys() | b.keys() if a.get(name) != b.get(name)}


class ModelRepairAdapter:
    artifact = ARTIFACT

    def __init__(
        self,
        env: Environment,
        version: int,
        folder: Path,
        *,
        items_client: Any,
        pbi: Any,
        sql_connector_factory: Any,
        recon_llm: Any,
        user_upn: str | None = None,
    ):
        self.env, self.version, self.folder = env, version, Path(folder)
        self.deps = dict(items_client=items_client, pbi=pbi, sql_connector_factory=sql_connector_factory, recon_llm=recon_llm, user_upn=user_upn)
        self.committed: ModelSpec = env.spec
        self.candidate: ModelSpec = self.committed.model_copy(deep=True)
        self.touched: set[str] = set()
        self.notes: list[str] = []
        self.staging = Path(env.run_dir) / "model" / ".repair.tmp"
        self.tmdl = read_model(self.folder)

    # -- classification -------------------------------------------------------------------

    def classify(self, errors: list[ValidationCheck], policy: RepairPolicy) -> list[ClassifiedError]:
        out = []
        for c in errors:
            if c.status != "fail":
                continue
            code = repair_code(c)
            out.append(ClassifiedError(c.fingerprint, c.object, c.id, code, policy.classify(code), c.message))
        return out

    # -- fixes ------------------------------------------------------------------------------

    def begin_attempt(self) -> None:
        self.candidate = self.committed.model_copy(deep=True)
        self.touched, self.notes = set(), []

    def deterministic_fix(self, errors: list[ClassifiedError]) -> None:
        for e in errors:
            if e.code != "FORMAT_STRING_INVALID":
                continue
            names = {n.casefold() for n in named_objects(e.message)} | {e.object.partition(":")[2].casefold()}
            fixed = False
            for m in self.candidate.measures:
                if m.name.casefold() in names and m.format_string:
                    m.format_string, fixed = None, True
                    self.touched.add(f"measure:{m.name}")
            for t in self.candidate.tables:
                for col in t.columns:
                    if col.name.casefold() in names and col.format_string:
                        col.format_string, fixed = None, True
                        self.touched.add(f"column:{t.name}.{col.name}")
            if not fixed:
                self.notes.append(f"no invalid format string found for {e.object}")

    def llm_fix(self, llm: Any, errors: list[ClassifiedError]) -> None:
        by_measure: dict[str, list[ClassifiedError]] = {}
        for e in errors:
            kind, _, name = e.object.partition(":")
            if kind == "measure":
                by_measure.setdefault(name, []).append(e)
            else:
                self.notes.append(f"{e.object}: only a measure can be regenerated")
        kpis = {k.name.casefold(): k for k in self.env.contract.kpis}
        for name, found in sorted(by_measure.items()):
            measure = next((m for m in self.candidate.measures if m.name == name), None)
            kpi = kpis.get(measure.kpi.casefold()) if measure else None
            if measure is None or kpi is None:
                self.notes.append(f"measure {name}: no approved KPI to regenerate it from")
                continue
            feedback = [f"The deployed measure [{name}] failed validation: {e.message}" for e in found]
            try:
                proposal = propose_measure_dax(kpi, self.candidate, llm, name, feedback)
            except DaxRejected as exc:
                self.notes.append(f"measure {name}: the new DAX was rejected ({exc.reason})")
                continue
            except (LlmTimeout, LlmUpstreamError, PromptRejected) as exc:
                self.notes.append(f"measure {name}: the model call failed ({exc})")
                continue
            if proposal.dax != measure.dax:
                measure.dax = proposal.dax
                self.touched.add(f"measure:{name}")

    # -- the scope guard --------------------------------------------------------------------

    def stage(self) -> None:
        """Serialize the candidate to the staging folder."""
        if self.staging.exists():
            shutil.rmtree(self.staging)
        generate_tmdl(self.candidate, self.staging, self.env.scope.sql_endpoint)

    def has_changes(self) -> bool:
        """Whether the candidate's files differ from the version in place. A fix that leaves the
        ModelSpec as it was can still change files, when the deployed files were edited by hand."""
        self.stage()
        return bool(changed_files(self.folder, self.staging))

    def files_of(self, obj: str) -> set[str]:
        kind, _, name = obj.partition(":")
        if kind == "measure":
            owner = next((t for t in self.tmdl.tables.values() if name.casefold() in {m.casefold() for m in t.measures}), None)
            return {f"definition/tables/{_file_name(owner.name)}"} if owner else set()
        if kind in ("column", "hierarchy"):
            table = name.split(".")[0]
            owner = next((t for t in self.tmdl.tables.values() if t.name.casefold() == table.casefold()), None)
            return {f"definition/tables/{_file_name(owner.name)}"} if owner else set()
        if kind == "relationship":
            return {"definition/relationships.tmdl"}
        return set()

    def scope_guard(self, errors: list[ClassifiedError]) -> list[str]:
        """The changed files of the staged candidate that are outside the failing objects (and the
        objects a fix touched). Empty means the attempt may be kept."""
        allowed: set[str] = set()
        for obj in {e.object for e in errors} | self.touched:
            allowed |= self.files_of(obj)
        return sorted(changed_files(self.folder, self.staging) - allowed)

    def discard(self) -> None:
        if self.staging.exists():
            shutil.rmtree(self.staging)
        self.candidate = self.committed.model_copy(deep=True)

    def take_notes(self) -> list[str]:
        notes, self.notes = self.notes, []
        return notes

    # -- keeping and validating an attempt --------------------------------------------------

    def validate(self, repair_attempt: int) -> ValidationRun:
        """Keep the staged candidate as the next version, then validate it."""
        run_dir = Path(self.env.run_dir)
        unversioned = lambda m: {**to_data(m), "version": 0}  # noqa: E731
        if unversioned(self.candidate) == unversioned(self.committed):
            spec = self.committed  # the files were restored from the ModelSpec: it keeps its version
        else:
            spec = self.candidate
            spec.version = self.committed.version + 1
            save_yaml(spec, run_dir / MODEL_FILE)
            save_yaml(spec, run_dir / "plans" / f"ModelSpec.v{spec.version}.yaml")
        self.version = _next_version(run_dir / "model")
        final = run_dir / "model" / f"v{self.version}"
        replace_file(self.staging, final)
        self.folder, self.committed = final, spec
        self.candidate = spec.model_copy(deep=True)
        self.tmdl = read_model(final)
        self.env.spec = spec
        return run_validation(
            self.env, final, self.version, folder_hash(final), spec=spec, repair_attempt=repair_attempt, **self.deps
        )

    def spec_hash(self) -> str:
        return canonical_hash(to_data(self.committed))
